def dataset_jsonld(d):
    dist = [{
        "@type": "DataDownload",
        "encodingFormat": d["format"],
        "contentSize": d["size_h"],
    }]
    if d["sample"]:
        dist.append({"@type": "DataDownload", "encodingFormat": "application/jsonl",
                     "contentUrl": SITE + d["sample"], "name": "Free 200-record sample"})
    return {
        "@context": "https://schema.org",
        "@type": "Dataset",
        "name": d["name"],
        "description": d["tagline"] + " " + d["provenance_long"],
        "url": f"{SITE}/data/{d['slug']}",
        "identifier": f"sha256:{d['sha256']}",
        "keywords": d["keywords"],
        "license": f"{SITE}/data/{d['slug']}#license",
        "isAccessibleForFree": False,
        "creator": {"@type": "Organization", "name": "Ledatic", "url": SITE},
        "provider": {"@type": "Organization", "name": "Ledatic", "url": SITE},
        "distribution": dist,
        "measurementTechnique": "Cryptographic provenance: SHA-256 leaves, Merkle root, Ed25519 witness signature anchored to a public entropy beacon pulse.",
    }


def faq_jsonld(d):
    return {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "mainEntity": [
            {"@type": "Question", "name": q,
             "acceptedAnswer": {"@type": "Answer", "text": a}}
            for q, a in d["faq"]
        ],
    }


