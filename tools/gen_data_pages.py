def main():
    os.makedirs(OUT, exist_ok=True)
    catalog = []
    sitemap_blocks = []
    for d in CATALOG:
        path = os.path.join(OUT, f"{d['slug']}.html")
        with open(path, "w") as f:
            f.write(page_html(d))
        print("wrote", os.path.relpath(path))
        catalog.append({
            "name": d["name"], "slug": d["slug"], "price_usd": d["price_usd"],
            "url": f"{SITE}/data/{d['slug']}", "buy_url": d["buy_url"],
            "records": d["records"], "size": d["size_h"], "format": d["format"],
            "sha256": d["sha256"], "witness_pulse": d["pulse"],
            "provenance_basis": d["provenance"], "license": "single-organization commercial",
        })
        sitemap_blocks.append(
            f"  <url>\n    <loc>{SITE}/data/{d['slug']}</loc>\n"
            f"    <lastmod>2026-07-02</lastmod>\n    <changefreq>weekly</changefreq>\n"
            f"    <priority>0.8</priority>\n  </url>"
        )
    cat = {"catalog": "ledatic-attested-data", "updated": "2026-07-02",
           "verify_note": "Every listing's provenance chain is independently re-verifiable; see each dataset page.",
           "datasets": catalog}
    with open(os.path.join(OUT, "catalog.json"), "w") as f:
        json.dump(cat, f, indent=2)
    print("wrote", os.path.relpath(os.path.join(OUT, "catalog.json")))
    print("\n--- sitemap <url> blocks to add ---")
    print("\n".join(sitemap_blocks))


if __name__ == "__main__":
    main()
